export function exportHtml(index: SkillIndex, outDir: string): void {
  mkdirSync(outDir, { recursive: true });

  // Index page
  const skillsHtml = index.skills.map(skill => {
    const tags = (skill.frontmatter.tags || []).map(t => `<span class="tag">${escapeHtml(t)}</span>`).join('');
    return `<li>
      <h3><a href="${encodeURIComponent(skill.id)}.html">${escapeHtml(skill.name)}</a></h3>
      <p>${escapeHtml(skill.frontmatter.description || 'No description')}</p>
      <div class="meta">${tags} <span>scope: ${escapeHtml(skill.frontmatter.scope || 'unknown')}</span></div>
    </li>`;
  }).join('');

  const indexBody = `
<header>
  <h1>Agent Skills</h1>
  <p class="meta">${index.skills.length} skill${index.skills.length === 1 ? '' : 's'} indexed</p>
</header>
<ul class="skill-list">
${skillsHtml}
</ul>`;

  writeFileSync(join(outDir, 'index.html'), pageTemplate('Agent Skills', indexBody));

  // Individual skill pages
  for (const skill of index.skills) {
    const tags = (skill.frontmatter.tags || []).map(t => `<span class="tag">${escapeHtml(t)}</span>`).join('');
    const contentHtml = markdownToHtml(skill.content);

    const body = `
<header>
  <p class="meta"><a href="index.html">← All skills</a></p>
  <h1>${escapeHtml(skill.name)}</h1>
  <p class="meta">${escapeHtml(skill.frontmatter.description || '')}</p>
  <div class="meta">${tags} <span>scope: ${escapeHtml(skill.frontmatter.scope || 'unknown')}</span></div>
</header>
<article>
${contentHtml}
</article>`;

    writeFileSync(join(outDir, `${skill.id}.html`), pageTemplate(skill.name, body));
  }

  // Try to copy any additional assets from skill directories
  for (const skill of index.skills) {
    try {
      const entries = require('fs').readdirSync(skill.path, { withFileTypes: true });
      for (const entry of entries) {
        if (entry.name.toLowerCase() === 'skill.md') continue;
        const src = join(skill.path, entry.name);
        const dest = join(outDir, 'assets', skill.id);
        mkdirSync(dest, { recursive: true });
        cpSync(src, join(dest, entry.name), { recursive: true });
      }
    } catch { /* ignore asset copy errors */ }
  }
}
